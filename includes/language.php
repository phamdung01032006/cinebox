function getSupportedLanguages() {
    return [
        "en" => "English",
        "vi" => "Tiếng Việt"
    ];
}

function isSupportedLanguage($language) {
    return array_key_exists($language, getSupportedLanguages());
}

function setCurrentLanguage($language) {
    $_SESSION["siteLanguage"] = isSupportedLanguage($language) ? $language : "en";
}

function getCurrentLanguage() {
    $language = $_SESSION["siteLanguage"] ?? "en";

    if(!isSupportedLanguage($language)) {
        $language = "en";
        $_SESSION["siteLanguage"] = $language;
    }

    return $language;
}

function getLanguageNativeName($language = null) {
    $language = $language ?? getCurrentLanguage();
    $languages = getSupportedLanguages();

    return $languages[$language] ?? $languages["en"];
}

